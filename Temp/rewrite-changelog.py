def write(rel, text):
    p = os.path.join(ROOT, rel)
    with open(p, 'wb') as f:
        f.write(text.replace('\r\n', '\n').encode('utf-8'))


def trash(path):
    name = os.path.basename(path)
    dst = os.path.join(TRASH, name)
    if os.path.exists(dst):
        dst += '.%d' % int(time.time() * 1000)
    os.rename(path, dst)


for ver, body in DOCS.items():
    src = os.path.join(CL, ver + '.md')
    # 1) 原文进 archive
    with open(src, 'rb') as f:
        raw = f.read()
    with open(os.path.join(ARCHIVE, ver + '.md'), 'wb') as f:
        f.write(raw)
    # 2) 原件进回收站
    trash(src)
    # 3) 写精简版
    write('CHANGELOG/' + ver + '.md', body.rstrip('\n') + '\n' + FOOT.format(v=ver))
    print('done', ver, len(raw), '->', len(body))

print('--- ok')
